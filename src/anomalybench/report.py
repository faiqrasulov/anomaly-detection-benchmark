"""Render metrics.json as a human-readable markdown report (reports/results.md)."""

from __future__ import annotations

from pathlib import Path


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = [
        "| " + " | ".join(header) + " |",
        "|" + "|".join(["---"] + ["---:"] * (len(header) - 1)) + "|",
    ]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _metric_table(m: dict, metric: str, rank_key: str | None) -> str:
    names = m["config"]["detectors"]
    datasets = list(m["datasets"])
    cell = {(r["dataset"], r["detector"]): r for r in m["results"]}
    order = sorted(names, key=lambda d: m["ranking"]["avg_rank_ap"][d])
    header = ["Detector"] + datasets + (["Avg rank"] if rank_key else [])
    rows = []
    for det in order:
        row = [names[det]]
        for ds in datasets:
            r = cell[(ds, det)]
            std = r[f"{metric}_std"]
            row.append(f"{r[metric]:.3f} ± {std:.3f}" if r["runs"] > 1 else f"{r[metric]:.3f}")
        if rank_key:
            row.append(f"{m['ranking'][rank_key][det]:.2f}")
        rows.append(row)
    return _table(header, rows)


def write_results_md(m: dict, path: str | Path) -> None:
    """Write every table behind the README to ``path``."""
    names = m["config"]["detectors"]
    ranked = m["config"]["ranked_datasets"]
    out = [
        "# Full results",
        "",
        "Generated by `make run` from `reports/metrics.json`. "
        "Mean ± standard deviation over seeds for stochastic detectors; one run otherwise.",
        "",
    ]

    out += ["## Datasets", ""]
    rows = []
    for ds, info in m["datasets"].items():
        rows.append(
            [
                ds,
                f"{info['n_before_subsampling']:,}",
                f"{info['n']:,}",
                str(info["d_raw"]),
                str(info["d"]),
                f"{info['n_anomalies']:,}",
                f"{info['anomaly_rate']:.2%}",
            ]
        )
    out += [
        _table(
            [
                "Dataset",
                "Rows available",
                "Rows used",
                "Raw features",
                "Features after preprocessing",
                "Anomalies",
                "Anomaly rate",
            ],
            rows,
        ),
        "",
    ]

    out += [
        "Diagnostics (computed with the labels, after scoring): how often rows are exact "
        "duplicates, and where anomalies differ from normal rows.",
        "",
    ]
    rows = [
        [
            ds,
            f"{info['dup_share_anomalies']:.0%}",
            f"{info['dup_share_normals']:.0%}",
            f"{info['distinct_anomaly_rows']:,}",
            f"{info['largest_shift_feature']} ({info['largest_shift']:+.2f})",
            f"{info['pca_components']} of {info['d']}",
            f"{info['shift_share_in_pca_subspace']:.0%}",
        ]
        for ds, info in m["datasets"].items()
    ]
    out += [
        _table(
            [
                "Dataset",
                "Anomaly rows with a duplicate",
                "Normal rows with a duplicate",
                "Distinct anomaly rows",
                "Largest mean shift (robust SDs)",
                "PCA components (90% var.)",
                "Mean shift inside PCA subspace",
            ],
            rows,
        ),
        "",
    ]

    excl = m["config"]["excluded_from_ranking"]
    out += ["## Average precision", ""]
    if excl:
        out += [
            f"Average ranks use {len(ranked)} datasets; excluded (fewer than "
            f"{m['config']['min_anomalies_for_ranking']} anomalies): {', '.join(excl)}.",
            "",
        ]
    out += [_metric_table(m, "ap", "avg_rank_ap"), ""]
    out += ["## ROC-AUC", "", _metric_table(m, "roc_auc", "avg_rank_roc_auc"), ""]
    out += [
        "## Precision at n (n = number of true anomalies)",
        "",
        _metric_table(m, "p_at_n", None),
        "",
    ]

    rk = m["ranking"]
    out += ["## Ranking statistics", ""]
    order = sorted(names, key=lambda d: rk["avg_rank_ap"][d])
    rows = [
        [
            names[d],
            f"{rk['avg_rank_ap'][d]:.2f}",
            f"{rk['avg_rank_roc_auc'][d]:.2f}",
            f"{rk['avg_rank_ap_all_datasets'][d]:.2f}",
            f"{rk['mean_ap'][d]:.3f}",
            f"{rk['mean_roc_auc'][d]:.3f}",
        ]
        for d in order
    ]
    out += [
        _table(
            [
                "Detector",
                "Avg rank (AP)",
                "Avg rank (ROC-AUC)",
                "Avg rank (AP, all datasets)",
                "Mean AP",
                "Mean ROC-AUC",
            ],
            rows,
        ),
        "",
    ]
    if rk["friedman"]:
        f = rk["friedman"]
        out += [
            f"Friedman test on AP ranks ({f['n_detectors']} detectors, {f['n_datasets']} "
            f"datasets): chi2 = {f['chi2']:.2f}, p = {f['p_value']:.4f}; Iman-Davenport "
            f"F = {f['f_stat']:.2f}, p = {f['f_p_value']:.4f}. Nemenyi critical difference "
            f"(alpha = 0.05, q = {rk['nemenyi_q_0.05']:.3f}): {rk['nemenyi_cd_0.05']:.2f} ranks.",
            "",
        ]

    st = m["seed_stability"]
    out += ["## Stability across seeds", ""]
    rows = [
        [
            names[d],
            f"{st['avg_rank_ap_min'][d]:.2f}",
            f"{st['avg_rank_ap_max'][d]:.2f}",
            f"{st['mean_ap_std_over_seeds'][d]:.4f}",
        ]
        for d in order
    ]
    out += [
        _table(
            [
                "Detector",
                "Best avg rank over seeds",
                "Worst avg rank over seeds",
                "Mean AP std over seeds",
            ],
            rows,
        ),
        "",
    ]
    out += [
        f"Kendall's tau between the average-rank orderings of any two seeds: min "
        f"{st['kendall_tau_min']:.3f}, mean {st['kendall_tau_mean']:.3f}.",
        "",
    ]
    rows = [
        [ds, ", ".join(names[d] for d in w)]
        for ds, w in st["best_detector_per_dataset_across_seeds"].items()
    ]
    out += [_table(["Dataset", "Best detector under any seed"], rows), ""]

    dd = m.get("kdd_dedup") or {}
    if dd:
        out += [
            "## KDD99 without duplicate records",
            "",
            "Average precision with one seed, before and after keeping only the first copy of "
            "every identical (features, label) record.",
            "",
        ]
        cols = list(dd)
        header = ["Detector"] + [f"{ds} (dups / dedup)" for ds in cols]
        rows = [
            [names[d]]
            + [f"{dd[ds]['ap_with_duplicates'][d]:.3f} / {dd[ds]['ap'][d]:.3f}" for ds in cols]
            for d in order
        ]
        out += [_table(header, rows), ""]
        rows = [
            [
                ds,
                f"{m['datasets'][ds]['n']:,} -> {dd[ds]['n']:,}",
                f"{m['datasets'][ds]['n_anomalies']:,} -> {dd[ds]['n_anomalies']:,}",
                f"{m['datasets'][ds]['anomaly_rate']:.2%} -> {dd[ds]['anomaly_rate']:.2%}",
                f"{m['datasets'][ds]['dup_share_anomalies']:.0%}",
                f"{m['datasets'][ds]['dup_share_normals']:.0%}",
            ]
            for ds in cols
        ]
        out += [
            _table(
                [
                    "Dataset",
                    "Rows",
                    "Anomalies",
                    "Anomaly rate (= AP of a random detector)",
                    "Anomaly rows with a duplicate",
                    "Normal rows with a duplicate",
                ],
                rows,
            ),
            "",
        ]

    ae = m.get("autoencoder_epochs") or {}
    if ae:
        epochs = list(next(iter(ae.values())))
        out += [
            "## Autoencoder: average precision vs training epochs (seed 0)",
            "",
            _table(
                ["Dataset"] + [f"{e} epochs" for e in epochs],
                [[ds] + [f"{ae[ds][e]:.3f}" for e in epochs] for ds in ae],
            ),
            "",
        ]

    ab = m["alert_budget"]
    out += [f"## Alert budgets on {ab['dataset']}", ""]
    budgets = list(next(iter(ab["table"].values())))
    header = ["Detector"] + [
        f"top {float(b):.1%} ({ab['table'][order[0]][b]['alerts']:,} alerts)" for b in budgets
    ]
    rows = []
    for d in sorted(names, key=lambda d: -ab["table"][d][budgets[1]]["precision"]):
        rows.append(
            [names[d]]
            + [
                f"P {ab['table'][d][b]['precision']:.2f} / R {ab['table'][d][b]['recall']:.2f}"
                for b in budgets
            ]
        )
    out += [
        "P = precision (share of alerts that are anomalies), R = recall.",
        "",
        _table(header, rows),
        "",
    ]

    c = m["contamination"]
    out += [
        f"## Contamination pitfalls on {c['dataset']}",
        "",
        "Isolation Forest, varying `contamination` (seed 0):",
        "",
    ]
    rows = [
        [
            str(r["contamination"]),
            f"{r['flagged']:,} ({r['flagged_share']:.2%})",
            f"{r['precision']:.3f}",
            f"{r['recall']:.3f}",
            f"{r['ap']:.4f}",
            f"{r['roc_auc']:.4f}",
        ]
        for r in c["iforest_contamination"]
    ]
    out += [
        _table(
            ["contamination", "Flagged by predict()", "Precision", "Recall", "AP", "ROC-AUC"], rows
        ),
        "",
    ]
    out += ["One-Class SVM (Nystroem + SGD), varying `nu` (seed 0):", ""]
    rows = [
        [
            str(r["nu"]),
            f"{r['flagged']:,} ({r['flagged_share']:.2%})",
            f"{r['precision']:.3f}",
            f"{r['recall']:.3f}",
            f"{r['ap']:.4f}",
            f"{r['roc_auc']:.4f}",
        ]
        for r in c["ocsvm_nu"]
    ]
    out += [
        _table(["nu", "Flagged by predict()", "Precision", "Recall", "AP", "ROC-AUC"], rows),
        "",
    ]

    out += [
        "## Runtime",
        "",
        "Median seconds per run (fit + score) on "
        f"{m['environment']['cpu']}, {m['environment']['threads']} threads.",
        "",
    ]
    datasets = list(m["datasets"])
    cell = {(r["dataset"], r["detector"]): r for r in m["results"]}
    rows = [
        [names[d]]
        + [f"{cell[(ds, d)]['fit_s'] + cell[(ds, d)]['score_s']:.2f}" for ds in datasets]
        + [f"{m['runtime'][d]['total_s_all_datasets']:.2f}"]
        for d in order
    ]
    out += [_table(["Detector"] + datasets + ["Total"], rows), ""]

    env = m["environment"]
    out += [
        "## Environment",
        "",
        ", ".join(f"{k} {v}" for k, v in env.items()) + ".",
        f"Wall time of the whole pipeline: {m['wall_time_s']:.0f} s.",
        "",
    ]
    Path(path).write_text("\n".join(out))
